import { McpServerConfig, McpToolDefinition, SdkTarget } from '../types.js';
import { extractToolParams, toCamelCase } from '../optimizer/analyzer.js';

function mapJsonTypeToTs(t: string): string {
  if (t.includes('integer') || t.includes('number')) return 'number';
  if (t.includes('boolean')) return 'boolean';
  if (t.includes('array')) return 'unknown[]';
  if (t.includes('object')) return 'Record<string, unknown>';
  return 'string';
}

function mapJsonTypeToPy(t: string): string {
  if (t.includes('integer')) return 'int';
  if (t.includes('number')) return 'float';
  if (t.includes('boolean')) return 'bool';
  if (t.includes('array')) return 'list[Any]';
  if (t.includes('object')) return 'dict[str, Any]';
  return 'str';
}

export interface GeneratedSdkFile {
  relativePath: string;
  content: string;
}

export function generateCodeModeSdk(
  server: McpServerConfig,
  tools: McpToolDefinition[],
  targets: SdkTarget[]
): GeneratedSdkFile[] {
  const out: GeneratedSdkFile[] = [];

  if (targets.includes('ts')) {
    const blocks: string[] = [
      `// Generated by mcp2cli — Anthropic Code-Mode typed TypeScript SDK for: ${server.name}`,
      `import { spawnSync } from 'node:child_process';`,
      '',
      `export function callMcpTool<T = unknown>(toolName: string, input: Record<string, unknown>): T {`,
      `  const bin = process.platform === 'win32' ? 'mcp2cli.cmd' : 'mcp2cli';`,
      `  const res = spawnSync(`,
      `    bin,`,
      `    ['run', ${JSON.stringify(server.name)}, toolName, '--req-json', JSON.stringify(input), '--output', 'json'],`,
      `    { encoding: 'utf8', shell: false }`,
      `  );`,
      `  if (res.status !== 0) {`,
      `    throw new Error(res.stderr || \`Tool \${toolName} failed with exit code \${res.status}\`);`,
      `  }`,
      `  return JSON.parse(res.stdout) as T;`,
      `}`,
      '',
    ];

    for (const tool of tools) {
      const fnName = toCamelCase(tool.name);
      const ifaceName = `${fnName.charAt(0).toUpperCase()}${fnName.slice(1)}Input`;
      const params = extractToolParams(tool);

      blocks.push(`export interface ${ifaceName} {`);
      for (const p of params) {
        if (p.description) {
          blocks.push(`  /** ${p.description.replace(/\*\//g, '* /')} */`);
        }
        blocks.push(`  ${JSON.stringify(p.wireName)}${p.required ? '' : '?'}: ${mapJsonTypeToTs(p.type)};`);
      }
      blocks.push(`}`, '');

      if (tool.description) {
        blocks.push(`/** ${tool.description.replace(/\*\//g, '* /')} */`);
      }
      blocks.push(
        `export function ${fnName}(input: ${ifaceName} = {} as ${ifaceName}): unknown {`,
        `  return callMcpTool(${JSON.stringify(tool.name)}, input as Record<string, unknown>);`,
        `}`,
        ''
      );
    }

    out.push({ relativePath: 'ts/index.ts', content: blocks.join('\n') });
  }

  if (targets.includes('py')) {
    const blocks: string[] = [
      `"""Generated by mcp2cli — Code-Mode typed Python SDK for: ${server.name}."""`,
      `from __future__ import annotations`,
      `import json`,
      `import shutil`,
      `import subprocess`,
      `from typing import Any`,
      '',
      `SERVER_NAME = ${JSON.stringify(server.name)}`,
      '',
      `def call_mcp_tool(tool_name: str, arguments: dict[str, Any] | None = None) -> Any:`,
      `    bin_path = shutil.which("mcp2cli") or "mcp2cli"`,
      `    proc = subprocess.run(`,
      `        [bin_path, "run", SERVER_NAME, tool_name, "--req-json", json.dumps(arguments or {}), "--output", "json"],`,
      `        capture_output=True,`,
      `        text=True,`,
      `        check=False,`,
      `    )`,
      `    if proc.returncode != 0:`,
      `        raise RuntimeError(proc.stderr.strip() or f"Tool {tool_name} failed ({proc.returncode})")`,
      `    return json.loads(proc.stdout)`,
      '',
    ];

    for (const tool of tools) {
      const fnName = tool.name.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();
      const params = extractToolParams(tool);
      const reqParams = params.filter((p) => p.required);
      const optParams = params.filter((p) => !p.required);
      const sigParts = [
        ...reqParams.map((p) => `${p.wireName.replace(/[^a-zA-Z0-9_]/g, '_')}: ${mapJsonTypeToPy(p.type)}`),
        ...optParams.map((p) => `${p.wireName.replace(/[^a-zA-Z0-9_]/g, '_')}: ${mapJsonTypeToPy(p.type)} | None = None`),
      ];
      blocks.push(`def ${fnName}(${sigParts.join(', ')}) -> Any:`);
      if (tool.description) {
        blocks.push(`    ${JSON.stringify(tool.description)}`);
      }
      blocks.push(`    payload: dict[str, Any] = {}`);
      for (const p of params) {
        const pyVar = p.wireName.replace(/[^a-zA-Z0-9_]/g, '_');
        blocks.push(`    if ${pyVar} is not None: payload[${JSON.stringify(p.wireName)}] = ${pyVar}`);
      }
      blocks.push(`    return call_mcp_tool(${JSON.stringify(tool.name)}, payload)`, '');
    }

    out.push({ relativePath: 'py/client.py', content: blocks.join('\n') });
  }

  return out;
}
