import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import {
  Mcp2CliError,
  SecretVault,
  assertNoControlChars,
  assertPathInside,
  assertSafeIdentifier,
  findReferencedEnvVars,
  redactServerSecrets,
  resolveSecretRef,
  toSkillName,
} from '../src/index.js';

describe('security & input hardening', () => {
  it('rejects control characters generated by hallucinating agents', () => {
    expect(() => assertNoControlChars('valid-name', 'name')).not.toThrow();
    expect(() => assertNoControlChars('bad\nname', 'name')).toThrow(Mcp2CliError);
    expect(() => assertNoControlChars('bad\rname', 'name')).toThrow(Mcp2CliError);
    expect(() => assertNoControlChars('bad\0name', 'name')).toThrow(Mcp2CliError);
  });

  it('rejects path traversal in identifiers and output paths', () => {
    expect(() => assertSafeIdentifier('../../.ssh', 'server')).toThrow(Mcp2CliError);
    expect(() => assertSafeIdentifier('a/b', 'server')).toThrow(Mcp2CliError);
    expect(() => assertPathInside('/tmp/skills', '../escape')).toThrow(Mcp2CliError);
    expect(assertPathInside('/tmp/skills', 'my-skill/SKILL.md')).toBe(
      path.resolve('/tmp/skills/my-skill/SKILL.md')
    );
  });

  it('normalizes arbitrary server names into agentskills.io compliant names', () => {
    expect(toSkillName('GitHub_MCP Server!')).toBe('github-mcp-server');
    expect(toSkillName('--My__App--')).toBe('my-app');
    expect(toSkillName('A'.repeat(100)).length).toBeLessThanOrEqual(64);
  });

  it('redacts raw secrets while keeping env:/file:/${VAR} references inspectable', () => {
    const redacted = redactServerSecrets({
      name: 'github',
      transport: 'http',
      url: 'https://mcp.example.com',
      headers: {
        Authorization: 'Bearer secret-abc-123',
        'X-Custom': 'env:MY_TOKEN',
      },
      env: {
        GITHUB_TOKEN: 'ghp_123456789',
        NODE_ENV: 'production',
        API_KEY: '${MY_API_KEY}',
      },
    });
    expect(redacted.headers?.['Authorization']).toBe('***REDACTED***');
    expect(redacted.headers?.['X-Custom']).toBe('env:MY_TOKEN');
    expect(redacted.env?.['GITHUB_TOKEN']).toBe('***REDACTED***');
    expect(redacted.env?.['NODE_ENV']).toBe('production');
    expect(redacted.env?.['API_KEY']).toBe('${MY_API_KEY}');
  });

  it('detects referenced env vars in untrusted project configs', () => {
    const vars = findReferencedEnvVars({
      command: 'npx',
      args: ['-y', '@example/mcp'],
      env: { TOKEN: '${GITHUB_TOKEN}' },
      headers: { Authorization: 'Bearer ${API_SECRET:-default}' },
    });
    expect(vars).toEqual(['GITHUB_TOKEN', 'API_SECRET']);
  });

  it('encrypts and decrypts secrets in SecretVault without native addons', async () => {
    const tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), 'mcp2cli-vault-'));
    try {
      const vault = new SecretVault(tmpDir);
      await vault.set('MY_TOKEN', 'super-secret-value');
      expect(await vault.listKeys()).toEqual(['MY_TOKEN']);
      expect(await vault.get('MY_TOKEN')).toBe('super-secret-value');
      expect(await vault.delete('MY_TOKEN')).toBe(true);
      expect(await vault.get('MY_TOKEN')).toBeUndefined();
    } finally {
      await fs.rm(tmpDir, { recursive: true, force: true });
    }
  });

  it('resolves env: and Bearer env: secret references without argv leakage', async () => {
    process.env['MCP2CLI_TEST_SECRET'] = 'tok-xyz';
    try {
      expect(await resolveSecretRef('env:MCP2CLI_TEST_SECRET')).toBe('tok-xyz');
      expect(await resolveSecretRef('Bearer env:MCP2CLI_TEST_SECRET')).toBe('Bearer tok-xyz');
    } finally {
      delete process.env['MCP2CLI_TEST_SECRET'];
    }
  });
});
